/**
 * Derive the FlowHRMS wordmark component from the official Flowacord logo.
 *
 * Reads public/brand/flowacord-logo-light.svg (the approved vector) and
 * writes src/components/brand/FlowHRMSWordmark.tsx. Nothing is redrawn:
 * the icon mark and the four outlined glyphs of "Flow" are copied with
 * their coordinates untouched; "acord" is dropped and "HRMS" is set in the
 * brand's secondary face (Poppins SemiBold Italic) on the same baseline.
 *
 * Re-run after any change to the source logo:  node scripts/build-wordmark.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "public/brand/flowacord-logo-light.svg";
const OUT = "src/components/brand/FlowHRMSWordmark.tsx";

const svg = readFileSync(SRC, "utf8");
// Capture attributes only: the source elements are self-closing, and the
// slash must not leak into the JSX that gets its own `/>`.
const els = [...svg.matchAll(/<(rect|path|polygon)\b([^>]*?)\s*\/?>/g)];
if (els.length !== 15) throw new Error(`expected 15 elements in ${SRC}, found ${els.length}`);

// Elements 0–5: the icon mark. 6–9: "Flow". 10–14: "acord" (dropped).
const mark = els
  .slice(0, 6)
  .map((m) => `      <${m[1]}${m[2].replace(/class="cls-(\d)"/, (_s, n) => `fill={FILL[${n}]}`)} />`)
  .join("\n");
const flow = els
  .slice(6, 10)
  .map((m) => {
    const d = (m[2].match(/\bd="([^"]+)"/) || [])[1];
    const p = (m[2].match(/points="([^"]+)"/) || [])[1];
    return d ? `        <path d="${d}" />` : `        <polygon points="${p}" />`;
  })
  .join("\n");

const out = `import { cn } from "@/lib/cn";
import { FLOWACORD } from "./FlowacordMark";

/**
 * The FlowHRMS wordmark — the product lockup, built from the approved
 * Flowacord logo, not drawn afresh. GENERATED by scripts/build-wordmark.mjs;
 * edit that script, not this file.
 *
 * Everything up to and including "Flow" is the official vector
 * (public/brand/flowacord-logo-light.svg, viewBox 652.69 × 113.84): the
 * icon mark and the four outlined glyphs of "Flow" in the company's
 * primary face, coordinates untouched. "acord" is replaced by "HRMS", set
 * in the brand's secondary face — Poppins SemiBold Italic — in the same
 * lavender, on the same baseline (y = 98.71) and to the same cap height.
 * That mirrors the two-part construction of the company mark exactly.
 *
 * The dark-background variant of the official logo is the same drawing at
 * a different scale with "Flow" in paper white, so one geometry serves
 * both tones and only the fill changes.
 */

/** Fill classes from the official file: 1 lavender-light, 2 lavender, 3 purple. */
const FILL = {
  1: FLOWACORD.lavenderLight,
  2: FLOWACORD.lavender,
  3: FLOWACORD.purple,
} as const;

const FLOW_INK = { light: FLOWACORD.navy, dark: FLOWACORD.paper } as const;

/** Right edge of the "w" is 334; capitals need a little air that lowercase "acord" did not. */
const HRMS_X = 352;
const BASELINE = 98.71;
/** Poppins cap height is 0.70 em; the "F" stands 57.3 units tall. */
const HRMS_SIZE = 82;
const VIEW_W = 612;
const VIEW_H = 113.84;

const FONT = "var(--font-poppins-display, var(--font-poppins, Poppins, sans-serif))";

export function FlowHRMSWordmark({
  height = 28,
  tone = "light",
  className,
  title = "FlowHRMS",
}: {
  height?: number;
  /** "light" = on white/paper. "dark" = on the navy ground. */
  tone?: "light" | "dark";
  className?: string;
  title?: string | null;
}) {
  const width = (height * VIEW_W) / VIEW_H;
  return (
    <svg
      width={width}
      height={height}
      viewBox={\`0 0 \${VIEW_W} \${VIEW_H}\`}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : "true"}
      focusable="false"
      className={className}
    >
      {title && <title>{title}</title>}
${mark}
      <g fill={FLOW_INK[tone]}>
${flow}
      </g>
      <text
        x={HRMS_X}
        y={BASELINE}
        fill={FLOWACORD.lavender}
        fontFamily={FONT}
        fontWeight={600}
        fontStyle="italic"
        fontSize={HRMS_SIZE}
        letterSpacing="-0.5"
      >
        HRMS
      </text>
    </svg>
  );
}

/**
 * Wordmark plus the parent-brand line, for headers and sign-in.
 * "by Flowacord" is text, not part of the mark: it takes the surface's
 * muted ink and is the first thing to drop on a narrow screen. A caller
 * that passes className owns the display value (e.g. "hidden md:inline-flex").
 */
export function FlowHRMSLockup({
  height = 28,
  tone = "light",
  byline = true,
  className,
}: {
  height?: number;
  tone?: "light" | "dark";
  byline?: boolean;
  className?: string;
}) {
  const sub = tone === "dark" ? "rgba(245,245,245,.72)" : "rgba(52,50,127,.72)";
  return (
    <span className={cn("items-baseline gap-2.5", className ?? "inline-flex")}>
      <FlowHRMSWordmark height={height} tone={tone} />
      {byline && (
        <span
          style={{
            fontFamily: FONT,
            fontWeight: 500,
            fontSize: Math.max(11, Math.round(height * 0.42)),
            letterSpacing: "0.01em",
            color: sub,
            whiteSpace: "nowrap",
          }}
        >
          by Flowacord
        </span>
      )}
    </span>
  );
}
`;

writeFileSync(OUT, out);
console.log(`${OUT} written from ${SRC} (${out.split("\n").length} lines)`);
